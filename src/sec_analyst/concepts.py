"""Financial concepts and their member tags from the given notebook."""

import duckdb
import pandas as pd


CONCEPTS = {   # the team's knowledge base: concept → (analyst phrases, member tags in precedence order, period type)
    "Revenue":    (["revenue", "revenues", "net sales", "sales", "turnover", "top line"],
                   ["Revenues", "SalesRevenueNet", "SalesRevenueGoodsNet", "SalesRevenueServicesNet", "RevenuesNetOfInterestExpense",
                    "RealEstateRevenueNet", "OilAndGasRevenue", "RegulatedAndUnregulatedOperatingRevenue", "ElectricUtilityRevenue",
                    "HealthCareOrganizationRevenue", "RevenueMineralSales", "RefiningAndMarketingRevenue", "ContractsRevenue"], "duration"),
    "NetIncome":  (["net income", "net profit", "net earnings", "profit", "earnings", "net loss", "bottom line"],
                   ["NetIncomeLoss", "NetIncomeLossAvailableToCommonStockholdersBasic", "ProfitLoss"], "duration"),
    "OperatingCashFlow": (["operating cash flow", "cash from operations", "cash generated by operations", "cash flow from operating activities"],
                   ["NetCashProvidedByUsedInOperatingActivities", "NetCashProvidedByUsedInOperatingActivitiesContinuingOperations"], "duration"),
    "Assets":     (["total assets", "assets", "balance sheet total"], ["Assets"], "instant"),
    "Liabilities": (["total liabilities", "liabilities"], ["Liabilities"], "instant"),
    "Equity":     (["shareholders equity", "stockholders equity", "shareholders funds", "book value", "equity"],
                   ["StockholdersEquity", "StockholdersEquityIncludingPortionAttributableToNoncontrollingInterest"], "instant"),
    "Cash":       (["cash and cash equivalents", "cash and equivalents", "cash"], ["CashAndCashEquivalentsAtCarryingValue", "Cash"], "instant"),
}


def register_concepts(
    connection: duckdb.DuckDBPyConnection,
) -> None:
    """Create the notebook's concept membership table."""
    rows = []

    for concept, (phrases, tags, period_type) in CONCEPTS.items():
        for priority, tag in enumerate(tags):
            rows.append(
                {
                    "concept": concept,
                    "tag": tag,
                    "priority": priority,
                    "period_type": period_type,
                }
            )

    members = pd.DataFrame(rows)
    connection.register("kb_df", members)
    connection.execute("CREATE TABLE kb AS SELECT * FROM kb_df")
